"""
Export S3DIS semantic segmentation results to PLY files.

The script writes:
  - rgb.ply: original point colors
  - gt.ply: ground-truth semantic colors
  - pred.ply: predicted semantic colors
  - error.ply: green correct, red wrong, gray ignored
  - legend.txt: class/color mapping
"""

import argparse
from pathlib import Path

import numpy as np


S3DIS_NAMES = [
    "ceiling",
    "floor",
    "wall",
    "beam",
    "column",
    "window",
    "door",
    "table",
    "chair",
    "sofa",
    "bookcase",
    "board",
    "clutter",
]

S3DIS_PALETTE = np.array(
    [
        [0, 200, 255],    # ceiling
        [180, 180, 180],  # floor
        [255, 170, 0],    # wall
        [255, 0, 0],      # beam
        [170, 0, 255],    # column
        [0, 120, 255],    # window
        [120, 70, 20],    # door
        [0, 180, 80],     # table
        [255, 0, 180],    # chair
        [120, 255, 0],    # sofa
        [0, 80, 120],     # bookcase
        [255, 255, 0],    # board
        [100, 100, 255],  # clutter
    ],
    dtype=np.uint8,
)


def write_ply(path, coord, color):
    path.parent.mkdir(parents=True, exist_ok=True)
    coord = coord.astype(np.float32, copy=False)
    color = np.clip(color, 0, 255).astype(np.uint8, copy=False)

    vertices = np.empty(
        coord.shape[0],
        dtype=[
            ("x", "<f4"),
            ("y", "<f4"),
            ("z", "<f4"),
            ("red", "u1"),
            ("green", "u1"),
            ("blue", "u1"),
        ],
    )
    vertices["x"] = coord[:, 0]
    vertices["y"] = coord[:, 1]
    vertices["z"] = coord[:, 2]
    vertices["red"] = color[:, 0]
    vertices["green"] = color[:, 1]
    vertices["blue"] = color[:, 2]

    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        f"element vertex {coord.shape[0]}\n"
        "property float x\n"
        "property float y\n"
        "property float z\n"
        "property uchar red\n"
        "property uchar green\n"
        "property uchar blue\n"
        "end_header\n"
    )
    with path.open("wb") as f:
        f.write(header.encode("ascii"))
        vertices.tofile(f)


def label_to_color(label):
    label = label.reshape(-1).astype(np.int64)
    color = np.zeros((label.shape[0], 3), dtype=np.uint8)
    valid = (label >= 0) & (label < len(S3DIS_PALETTE))
    color[valid] = S3DIS_PALETTE[label[valid]]
    color[~valid] = np.array([40, 40, 40], dtype=np.uint8)
    return color


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--room",
        default="data/s3dis/Area_5/office_1",
        help="Path to a preprocessed S3DIS room folder.",
    )
    parser.add_argument(
        "--pred",
        default="exp/s3dis/ptv3-rpe-lowmem/result/Area_5-office_1_pred.npy",
        help="Path to *_pred.npy generated by tools/test.py.",
    )
    parser.add_argument(
        "--out",
        default="exp/s3dis/ptv3-rpe-lowmem/vis/Area_5-office_1",
        help="Output folder for PLY files.",
    )
    parser.add_argument(
        "--batch",
        action="store_true",
        help="Batch mode: auto-discover all rooms from --room parent and --pred parent.",
    )
    parser.add_argument(
        "--sample",
        type=int,
        default=0,
        help="Randomly export this many points. Use 0 to export all points.",
    )
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    if args.batch:
        # Use defaults: scan result dir, derive room dir from pred dir pattern
        pred_dir = Path(args.pred).parent
        out_base = Path(args.out).parent
        # Guess room parent: if pred_dir is "exp/.../result", room is "data/s3dis/"
        room_parent = pred_dir.parents[2] / "data" / "s3dis"
        if not room_parent.is_dir():
            room_parent = Path("data/s3dis")

        npred = 0
        for pred_file in sorted(pred_dir.glob("*_pred.npy")):
            stem = pred_file.stem
            area_room = stem.rsplit("_pred", 1)[0]
            parts = area_room.split("-", 1)
            if len(parts) != 2:
                continue
            area, room_name = parts[0], parts[1]
            room_path = room_parent / area / room_name
            out_path = out_base / area_room

            if not room_path.is_dir():
                print(f"  [SKIP] Room folder not found: {room_path}")
                continue

            print(f"Visualizing: {area_room}")
            visualize_one(room_path, pred_file, out_path, args.sample, args.seed)
            npred += 1
        print(f"Batch visualization done: {npred} rooms.")
    else:
        visualize_one(Path(args.room), Path(args.pred), Path(args.out), args.sample, args.seed)


def visualize_one(room, pred_path, out, sample, seed):
    coord = np.load(room / "coord.npy")
    color = np.load(room / "color.npy")
    segment = np.load(room / "segment.npy").reshape(-1)
    pred = np.load(pred_path).reshape(-1)

    if coord.shape[0] != pred.shape[0]:
        raise ValueError(
            f"Prediction length {pred.shape[0]} does not match coord length {coord.shape[0]}"
        )
    if coord.shape[0] != segment.shape[0]:
        raise ValueError(
            f"Segment length {segment.shape[0]} does not match coord length {coord.shape[0]}"
        )

    if sample and sample < coord.shape[0]:
        rng = np.random.default_rng(seed)
        index = rng.choice(coord.shape[0], size=sample, replace=False)
        coord = coord[index]
        color = color[index]
        segment = segment[index]
        pred = pred[index]

    rgb = color.astype(np.float32)
    if rgb.max() <= 1.0:
        rgb = rgb * 255.0
    rgb = rgb.astype(np.uint8)

    gt_color = label_to_color(segment)
    pred_color = label_to_color(pred)

    error_color = np.zeros((coord.shape[0], 3), dtype=np.uint8)
    ignore = segment < 0
    correct = (pred == segment) & ~ignore
    wrong = (pred != segment) & ~ignore
    error_color[correct] = np.array([0, 220, 0], dtype=np.uint8)
    error_color[wrong] = np.array([255, 40, 40], dtype=np.uint8)
    error_color[ignore] = np.array([120, 120, 120], dtype=np.uint8)

    write_ply(out / "rgb.ply", coord, rgb)
    write_ply(out / "gt.ply", coord, gt_color)
    write_ply(out / "pred.ply", coord, pred_color)
    write_ply(out / "error.ply", coord, error_color)

    with (out / "legend.txt").open("w", encoding="utf-8") as f:
        for idx, (name, color_) in enumerate(zip(S3DIS_NAMES, S3DIS_PALETTE)):
            f.write(f"{idx}: {name} rgb={color_.tolist()}\n")
        f.write("\nerror.ply: green=correct, red=wrong, gray=ignored\n")

    print(f"Saved visualization files to: {out}")


if __name__ == "__main__":
    main()
